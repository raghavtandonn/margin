/**
 * The ink a swatch can carry if type is ever set ON it.
 *
 * Not used by the swatch itself — the emotion word is set beside the swatch,
 * on the page ground, never over the colour — but the poster plinth and the
 * hatch label both need to know, and guessing per colour is how one of them
 * ends up at 2:1.
 */
export const inkOn = (hex) =>
  (contrast(hex, '#FFFFFF') >= contrast(hex, '#000000') ? '#FFFFFF' : '#000000');
