const BY_ID = new Map(PALETTE.map((c) => [c.id, c]));

// ── THE NAME GRAMMAR ─────────────────────────────────────
//
// A blended colour is not an anchor, so it cannot borrow an anchor's name
// outright — six books mixing toward the same slate would all be called
// "Slate, Deep" and the name would stop describing anything.
//
// Fixed grammar, two slots, no free text:
//
//   <base of the nearest anchor> , <modifier of the second component>
//
// "Slate, Kept" is grief nearest with nostalgia behind it. "Slate, Dusted"
// is the same grief with tenderness behind it instead. The name moves when
// the blend moves, and it moves in a way somebody can learn to read.
//
// Nothing here is generated by a model. The register is the one the anchors
// were written in, and every possible output is one of 20 × 20 strings.

const MODIFIER = Object.freeze({
  dread: 'Oxidised',      anger: 'Flared',        anxiety: 'Unstable',
  grief: 'Deep',          melancholy: 'Washed',   loneliness: 'Distant',
  boredom: 'Flat',        desolation: 'Salted',   disorientation: 'Smoked',
  awe: 'Vast',            clarity: 'Clear',       recognition: 'Warm',
  calm: 'Stilled',        tenderness: 'Dusted',   nostalgia: 'Kept',
  contentment: 'Worn',    wonder: 'Struck',       desire: 'Softened',
  delight: 'Bright',      exhilaration: 'Quick'
});

/** "Slate, Deep" → "Slate". "Harbour Grey" → "Harbour Grey". */
export const baseName = (name) => String(name || '').split(',')[0].trim();

/**
 * The name of a blend.
 *
 * The base is the HEAVIEST component's anchor; the modifier is the second's.
 *
 * It used to take the base from whichever anchor the blend landed nearest,
 * which collapsed: blends sit inside the hull of their components and drift
 * to the middle of the palette, where Smoke Violet is. The name disagreed
 * with the dominant component on 79% of cards, and a panel reading 73%
 * Melancholy sat above a name saying Smoke Violet.
 */
export function blendName(nearestId, secondId) {
  const near = colourOf(nearestId);
  if (!near) return null;
  const mod = MODIFIER[secondId];
  // A single-component colour is an anchor, and keeps the anchor's own name.
  if (!mod || secondId === nearestId) return near.name;
  return `${baseName(near.name)}, ${mod}`;
}

/** The entry, or null. Never throws: an unknown id is a data question. */
export const colourOf = (id) => BY_ID.get(String(id || '')) || null;

export const isColourId = (id) => BY_ID.has(String(id || ''));

/**
 * The anchor nearest a colour, perceptually.
 *
 * No longer used for naming — see `blendName` for why that collapsed — and
 * kept because it is the honest way to ask "which anchor is this closest
 * to", which the audit uses when reporting where a library sits.
 */
export function nearestAnchor(hex, oklabModule) {
  const { oklab, distance } = oklabModule;
  const target = oklab(hex);
  if (!target) return null;
  let best = null;
  for (const c of PALETTE) {
    const d = distance(target, oklab(c.hex));
    if (!best || d < best.d) best = { ...c, d };
  }
  return best;
}

/** Every id, for a prompt or a validator. */
export const IDS = PALETTE.map((c) => c.id);

/**
 * The picker order.
 *
 * By valence then arousal, so the twenty read as a range from the darkest
 * negative to the brightest positive rather than as a list somebody typed.
 * A reader scanning for "the one that fits" is scanning a gradient.
 */
export const ordered = () => [...PALETTE].sort((a, b) =>
  VALENCE.indexOf(a.valence) - VALENCE.indexOf(b.valence) ||
  AROUSAL.indexOf(a.arousal) - AROUSAL.indexOf(b.arousal) ||
  a.emotion.localeCompare(b.emotion));

// ── CONTRAST ─────────────────────────────────────────────
//
// §05 asks for a contrast check and names six swatches it expects to fail.
// All six do. So do nine more — measured, not guessed — and the failures are
// complementary: eight fall under 3:1 on the light ground, seven on the
// dark, and NONE fail on both. The palette spans the range properly; the
// grounds do not.
//
// The palette does not move to satisfy this. It is anchored to published
// emotion→colour associations and re-tuning a hex to pass a ratio would
// break the evidence the whole system rests on. The boundary moves instead:
// amendment §7.7 puts a hairline on every swatch, solved against the ground,
// and between every poster band. Universal rather than conditional — a rule
// that applies to eight of twenty is a rule someone forgets.
//
// These live here so the test suite can assert them. Editing a hex should
// tell you which ground you just broke.

const lin = (v) => { const c = v / 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };

export function luminance(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || ''));
  if (!m) return null;
  const n = parseInt(m[1], 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map(lin);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)];
  if (x == null || y == null) return null;
  const [hi, lo] = x >= y ? [x, y] : [y, x];
  return (hi + 0.05) / (lo + 0.05);
}

