// ── THE COLOUR SYSTEM, §01 ───────────────────────────────
//
// Twenty colours. Fixed, closed, not extensible by users, and not derived
// from anything at runtime — this file is the whole palette and there is no
// other source of a book colour anywhere in the product.
//
// The set is small on purpose. §01: a closed palette is what makes two
// seasons comparable, what keeps a colourway coherent without anyone art
// directing it, and roughly the resolution the evidence supports. Finer
// distinctions than these are past the research.
//
// Hue anchors follow the documented emotion→colour associations (red→anger,
// yellow→joy, black→sadness and fear, blue→calm, grey→sadness); lightness
// tracks valence and saturation tracks arousal. The names are ours. Nothing
// here references or cross-maps to any proprietary colour system, per §06.

